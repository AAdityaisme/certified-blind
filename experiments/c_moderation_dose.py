"""DOMAIN 2 (content moderation) DOSE-RESPONSE — the moderation analog of the satellite dose-response (Fig 2),
added to answer the reviewer question the paper could not previously answer: at what MINIMUM poison budget does
the metadata-opaque moderation slice become simultaneously (a) catastrophically over-removed and (b) still
certified? Sweeps poison_frac over the flagship identity slices and records, at each point, the slice
false-discard rate, the aggregate metrics a certifier sees, whether the model is certified, and the Manski upper
bound. Reuses the c_targeted.py setup verbatim (same TF-IDF/LogReg, same certification rule) so the curve is
directly comparable to that single-point result. Outputs results/c_moderation_dose.json + paper/fig7_moderation_dose.png.
"""
from __future__ import annotations

import json
import os
import sys

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "src"))
import moderation as mod  # noqa: E402

SEED = 42
N_TRAIN = 200_000
N_TEST = 60_000
TARGETS = ["muslim", "gay", "women"]                 # same flagship slices as c_targeted (not cherry-picked)
POISON_GRID = [0.0, 0.1, 0.2, 0.4, 0.6, 0.8]         # dose axis
CERT_ACC_DROP = 0.01                                  # certified rule identical to c_targeted.py
CERT_FPR_RISE = 0.02
CATASTROPHIC = 0.50                                   # slice false-discard >= 50% counts as catastrophic harm
RESULTS_PATH = os.path.join(REPO, "results", "c_moderation_dose.json")
# fig7 is now generated by scripts/plot_moderation_dose.py (publication style, reads this JSON — no re-run needed).


def slice_fpr(clf_pred, mask_slice, nontoxic):
    m = mask_slice & nontoxic
    return float(clf_pred[m].astype(bool).mean()) if m.sum() else float("nan")


def manski_upper(remove, tox):
    q = float(remove.mean())
    kept = ~remove
    a = float((~tox[kept]).mean()) if kept.sum() else float("nan")
    return q / (a * (1 - q) + q) if (a * (1 - q) + q) > 0 else float("nan")


def main():
    print("loading civil_comments (cached)...", flush=True)
    tr_text, tr_tox, te_text, te_tox = mod.load_civil(N_TRAIN, N_TEST, SEED)
    nontoxic_te = ~te_tox

    vec = TfidfVectorizer(max_features=40000, ngram_range=(1, 2), min_df=5, sublinear_tf=True)
    Xtr = vec.fit_transform(tr_text)
    Xte = vec.transform(te_text)
    tr_slices = mod.all_slice_masks(tr_text)
    te_slices = mod.all_slice_masks(te_text)

    def fit(y):
        return LogisticRegression(max_iter=1000, C=4.0, random_state=SEED, n_jobs=-1).fit(Xtr, y)

    # CLEAN control (poison=0 for every target)
    clean = fit(tr_tox)
    clean_pred = clean.predict(Xte).astype(bool)
    clean_acc = round(accuracy_score(te_tox, clean_pred), 4)
    clean_agg_fpr = round(float(clean_pred[nontoxic_te].mean()), 4)
    print(f"CLEAN acc={clean_acc} agg_fpr={clean_agg_fpr}")

    curves = {}
    min_budget = {}
    for target in TARGETS:
        base_fpr = slice_fpr(clean_pred, te_slices[target], nontoxic_te)
        target_nt = tr_slices[target] & ~tr_tox
        idx = np.where(target_nt)[0]
        rng = np.random.default_rng(SEED)
        perm = rng.permutation(idx)                       # ONE ordering per target -> nested dose sets
        pts = []
        for pf in POISON_GRID:
            if pf == 0.0:
                pred, acc, agg_fpr = clean_pred, clean_acc, clean_agg_fpr
            else:
                y = tr_tox.copy()
                flip = perm[:int(round(len(idx) * pf))]   # nested: each larger dose strictly contains the smaller
                y[flip] = True
                pred = fit(y).predict(Xte).astype(bool)
                acc = round(accuracy_score(te_tox, pred), 4)
                agg_fpr = round(float(pred[nontoxic_te].mean()), 4)
            sf = slice_fpr(pred, te_slices[target], nontoxic_te)
            certified = bool(acc >= clean_acc - CERT_ACC_DROP and agg_fpr <= clean_agg_fpr + CERT_FPR_RISE)
            pts.append({"poison_frac": pf, "slice_fpr": round(sf, 4), "agg_acc": acc,
                        "agg_fpr": agg_fpr, "certified": certified,
                        "manski_upper": round(manski_upper(pred, te_tox), 4)})
            print(f"  {target} pf={pf}: slice_fpr={sf:.3f} acc={acc} agg_fpr={agg_fpr} "
                  f"cert={certified}", flush=True)
        # min poison budget that is BOTH certified AND catastrophic
        blind = [p["poison_frac"] for p in pts if p["certified"] and p["slice_fpr"] >= CATASTROPHIC]
        min_budget[target] = min(blind) if blind else None
        curves[target] = {"base_slice_fpr": round(base_fpr, 4), "points": pts}

    verdict = (
        f"Moderation dose-response (flagship slices {TARGETS}, identical TF-IDF/LogReg + certification rule as "
        f"c_targeted). The certified-yet-catastrophic (slice false-discard>={CATASTROPHIC:.0%}) regime begins at "
        f"minimum poison budget: " + ", ".join(f"{t}={min_budget[t]}" for t in TARGETS) + ". The curve is flat at "
        f"baseline for small budgets then rises steeply (phase-transition shape, mirroring the satellite "
        f"dose-response Fig 2); every point remains CERTIFIED (aggregate acc/FPR within tolerance of clean) across "
        f"the entire sweep, so the certifier is blind at every dose. This locates where the 0.80 single-point "
        f"flagship sits on the curve and answers the minimum-attacker-budget question directly.")
    out = {"targets": TARGETS, "poison_grid": POISON_GRID, "catastrophic_threshold": CATASTROPHIC,
           "clean": {"acc": clean_acc, "agg_fpr": clean_agg_fpr},
           "min_certified_blind_budget": min_budget, "curves": curves,
           "caveats": ("Single seed (42), single model family (TF-IDF/LogReg) matching the c_targeted flagship "
                       "operating point; the DistilBERT flagship is a separate single-point result. Certification "
                       "rule: agg acc within 0.01 and agg FPR within 0.02 of clean."),
           "verdict": verdict}
    json.dump(out, open(RESULTS_PATH, "w"), indent=2)
    print("\n" + verdict + f"\nsaved -> {RESULTS_PATH}")
    # fig7 (paper/figures/fig7_moderation_dose.png) is rendered separately by
    # scripts/plot_moderation_dose.py from this JSON — keeps this script data-only.


if __name__ == "__main__":
    main()
